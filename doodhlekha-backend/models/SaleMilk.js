const mongoose = require("mongoose");

/*
|--------------------------------------------------------------------------
| SALE MILK MODEL
|--------------------------------------------------------------------------
|
| IMPORTANT:
|
| Sale Milk manually create नहीं होगा।
|
| Customer को दिया गया actual milk:
|
| CustomerMilkLog
|
| में store होगा।
|
| यह model legacy / backward compatibility के लिए रखा गया है।
|
|--------------------------------------------------------------------------
*/

const saleMilkSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | USER / FARMER
    |--------------------------------------------------------------------------
    |
    | हर farmer का data अलग रहेगा।
    |
    */

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | DATE
    |--------------------------------------------------------------------------
    */

    date: {
      type: Date,
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | TOTAL MILK
    |--------------------------------------------------------------------------
    */

    totalMilk: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | MORNING SALE
    |--------------------------------------------------------------------------
    */

    morningSale: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | EVENING SALE
    |--------------------------------------------------------------------------
    */

    eveningSale: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | REMAINING MILK
    |--------------------------------------------------------------------------
    */

    remainingMilk: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | NOTES
    |--------------------------------------------------------------------------
    */

    notes: {
      type: String,
      trim: true,
      default: "",
      maxlength: 500,
    },
  },
  {
    timestamps: true,
  },
);

/*
|--------------------------------------------------------------------------
| INDEXES
|--------------------------------------------------------------------------
*/

/*
 * Farmer + Date
 */
saleMilkSchema.index({
  user: 1,
  date: -1,
});

/*
 * Farmer + Date ascending
 */
saleMilkSchema.index({
  user: 1,
  date: 1,
});

/*
|--------------------------------------------------------------------------
| EXPORT
|--------------------------------------------------------------------------
*/

module.exports = mongoose.model("SaleMilk", saleMilkSchema);
