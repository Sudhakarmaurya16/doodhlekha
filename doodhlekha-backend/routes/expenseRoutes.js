const express = require("express");

const authMiddleware = require("../middleware/authMiddleware");

const {
  createExpense,
  getExpenses,
  getTodayExpense,
  getMonthlyExpense,
  updateExpense,
  deleteExpense,
} = require("../controllers/expenseController");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| DOODHLEKHA - EXPENSE ROUTES
|--------------------------------------------------------------------------
|
| Base URL:
|
| /api/expenses
|
| सभी routes protected हैं।
|
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| AUTH MIDDLEWARE
|--------------------------------------------------------------------------
|
| अब हर request में:
|
| req.user.id
|
| available रहेगा।
|
|--------------------------------------------------------------------------
*/

router.use(authMiddleware);

/*
|--------------------------------------------------------------------------
| CREATE EXPENSE
|--------------------------------------------------------------------------
|
| POST
| /api/expenses
|
|--------------------------------------------------------------------------
*/

router.post("/", createExpense);

/*
|--------------------------------------------------------------------------
| GET ALL EXPENSES
|--------------------------------------------------------------------------
|
| GET
| /api/expenses
|
| Optional:
|
| /api/expenses?startDate=2026-08-01&endDate=2026-08-31
|
| /api/expenses?category=feed
|
|--------------------------------------------------------------------------
*/

router.get("/", getExpenses);

/*
|--------------------------------------------------------------------------
| GET TODAY EXPENSE
|--------------------------------------------------------------------------
|
| GET
| /api/expenses/today
|
|--------------------------------------------------------------------------
*/

router.get("/today", getTodayExpense);

/*
|--------------------------------------------------------------------------
| GET MONTHLY EXPENSE
|--------------------------------------------------------------------------
|
| GET
| /api/expenses/monthly?year=2026&month=8
|
|--------------------------------------------------------------------------
*/

router.get("/monthly", getMonthlyExpense);

/*
|--------------------------------------------------------------------------
| UPDATE EXPENSE
|--------------------------------------------------------------------------
|
| PUT
| /api/expenses/:id
|
|--------------------------------------------------------------------------
*/

router.put("/:id", updateExpense);

/*
|--------------------------------------------------------------------------
| DELETE EXPENSE
|--------------------------------------------------------------------------
|
| DELETE
| /api/expenses/:id
|
|--------------------------------------------------------------------------
*/

router.delete("/:id", deleteExpense);

/*
|--------------------------------------------------------------------------
| EXPORT
|--------------------------------------------------------------------------
*/

module.exports = router;
